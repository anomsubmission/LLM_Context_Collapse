"""Render final supplementary tables from immutable, reviewed analysis outputs."""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
ANALYSIS = ROOT / "revision/four_day_revision/analysis"
SOURCES: dict[str, str] = {}


def load(rel: str):
    path = ANALYSIS / rel
    SOURCES[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
    return json.loads(path.read_text())


def rows(rel: str):
    path = ANALYSIS / rel
    SOURCES[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
    return list(csv.DictReader(path.open()))


def pct(x, digits=2):
    return f"{100 * float(x):.{digits}f}"


def interval(item):
    return f"{pct(item['estimate'])} [{pct(item['ci_low'])}, {pct(item['ci_high'])}]"


def table(caption, label, columns, header, body):
    return "\n".join([
        r"\begin{table}[p]", r"\centering\color{blue}",
        "\\caption{" + caption + "}", "\\label{" + label + "}",
        r"\footnotesize", r"\begin{adjustbox}{max width=\textwidth}",
        "\\begin{tabular}{" + columns + "}", r"\toprule", header + r" \\",
        r"\midrule", *[r + r" \\" for r in body], r"\bottomrule",
        r"\end{tabular}", r"\end{adjustbox}", r"\end{table}", "",
    ])


